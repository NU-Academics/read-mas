"""A tool to generate code from READ-MAS agent designs."""

from litellm import completion
from loguru import logger
import re
from typing import Optional, Dict, Any
from google.adk.tools.tool_context import ToolContext
from google.adk.tools.base_tool import BaseTool


CODE_GENERATOR_TOOL_SYSTEM_PROMPT = """Generate code based on the following software design specification:

    {design_output}

    Provide complete, executable code that implements the design. 
        
    ## CRITICAL TEST REQUIREMENTS:
    - **FORBIDDEN**: DO NOT write unit tests - only generate the function implementation code
    - Generate ONLY the function implementation that solves the problem
    - Return only the code without explanations or markdown formatting unless the code itself requires markdown.
    """
    
def generate_code(design_output: str) -> str:
  """Generate code using an LLM using the input from a design agent.

  Args:
      design_output: The software design document obtained from the single agent tool in a string format

  Returns:
      The generated code with no extra text
  """

  try:
    # TODO: this can be an environment variable
    code_model = "ollama/gpt-oss:20b"
    # code_model="gemini/gemini-2.5-pro"
    response = completion(
        model=code_model,
        messages=[
            {"role": "user", "content": CODE_GENERATOR_TOOL_SYSTEM_PROMPT.format(design_output=design_output)},
        ],
    )

    result = response.choices[0].message.content
    logger.info(f"Code generated by generate_code tool using {code_model}: {result}")
    return result

  except Exception as e:
    raise RuntimeError(f"Failed to generate code: {str(e)}") from e
