"""Function to directly generate code using LLM."""

from litellm import acompletion
from loguru import logger
from eval.utils.constants import CODING_MODEL


EVAL_CODER_SYSTEM_MESSAGE = (
    "You are a Python code completer. Complete the given Python function using the "
    "provided design context as guidance. Output ONLY valid Python code — no markdown "
    "fences, no prose, no explanations, no tests."
)

EVAL_CODER_USER_PROMPT = """Complete this Python function:

{original_prompt}

Design context (use as implementation guidance only):
<design>
{design_output}
</design>

REQUIREMENTS:
- Return ONLY the bare function implementation — no class wrapper, no if __name__ == '__main__'
- Use the EXACT function name and parameter names from the function stub above
- Do NOT call any helper that is not defined inline in your response
- Do NOT add isinstance() checks or raise exceptions for edge cases
- Limit docstrings and comments to at most 2 sentences
- No unit tests"""


async def generate_eval_code(design_output: str, original_prompt: str = "") -> str:
  try:
    response = await acompletion(
        model=CODING_MODEL,
        messages=[
            {"role": "system", "content": EVAL_CODER_SYSTEM_MESSAGE},
            {
                "role": "user",
                "content": EVAL_CODER_USER_PROMPT.format(
                    original_prompt=original_prompt,
                    design_output=design_output,
                ),
            },
        ],
    )
    result = response.choices[0].message.content
    logger.info(f"Code generated by generate_code tool using {CODING_MODEL}: {result}")
    return result
  except Exception as e:
    raise RuntimeError(f"Failed to generate code: {str(e)}") from e